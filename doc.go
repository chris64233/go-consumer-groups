// Package consumergroups 提供消费组协调服务：以单调递增的分配版本
// （generation）隔离新旧成员操作，管理组成员、确定性分区分配、
// 协作式再均衡、会话超时与位点提交，并支持状态持久化。
//
// 核心不变量：
//   - 每次成员变化（加入/离开/超时剔除）都使分配版本 +1，并生成该版本的
//     目标所有权；与当前有效所有权的差异构成待撤销集合；
//   - 旧所有者确认撤销（或离开/超时被强制回收）之前，新所有者不能取得
//     分区，未受影响的分区继续由原成员消费；
//   - 撤销确认必须精确匹配组、成员、分配版本与分区集合，漏报、多报或
//     旧版本确认一律被拒绝；确认可安全重试；
//   - 携带旧分配版本的心跳、位点提交与撤销确认一律被拒绝；
//   - 只有当前有效所有者能提交位点：待撤销分区在确认前可由旧所有者
//     提交最终位点，转移完成后旧成员的迟到提交被栅栏；
//   - 位点默认单调递增；幂等请求号去重提交，同请求号不同内容构成冲突。
