// Package consumergroups 提供消费组协调服务：以单调递增的分配版本
// （generation）隔离新旧成员操作，管理动态成员、静态成员身份（static
// membership）与会话栅栏、确定性分区分配、协作式（cooperative）两阶段再均衡、
// 两级会话超时与位点提交，并支持状态持久化。
//
// 协作式再均衡的核心不变量：
//   - 每次「真正的」成员变化（加入/离开/超时剔除/静态实例清退）都使分配版本 +1，
//     并发布该版本的目标所有权；新旧版本中所有者不变的分区「未受影响」，继续由
//     原成员消费，不会一次性撤销全部分区；
//   - 在两个在线成员之间转移的分区先进入待撤销状态：旧所有者确认撤销之前，
//     新所有者不能取得该分区（生效所有权仍指向旧所有者）；
//     无主分区立即分派，离开/超时/被清退成员的剩余分区由协调器强制回收；
//   - 撤销确认必须精确匹配组、会话、分配版本与分区集合，可幂等重试，
//     漏项、额外分区或旧版本确认一律被拒绝，不能提前完成整个再均衡；
//   - 全体义务成员确认完毕后版本在同一 generation 内收敛为 stable；
//   - 只有分区当前生效所有者能提交位点：待撤销分区在确认前可由旧所有者提交
//     最终位点，一旦转移完成，旧成员的迟到提交被所有权栅栏阻止；
//   - 心跳、离开、超时扫描与撤销确认在同一把锁内串行，只能推动一条单调的
//     版本状态机（stable -> revoking -> stable），全部协调状态持久化。
//
// 静态成员身份（JoinStatic）的额外不变量：
//   - 成员以稳定的实例标识（InstanceID）加入，分区所有权挂在该标识下；每次
//     成功加入（重连/并发进程接管）获得单调递增的会话版本（SessionVersion）；
//   - 会话超时后实例在保留期（Retention）内仅「暂时离线」：不推进分配版本、
//     不转移其分区，协调器据此区分暂时离线与真正退出；保留期内以更高会话版本
//     重连继续原分配（Rejoined）；
//   - 只有超过保留期、主动 LeaveStatic 或被管理员 RemoveInstance 才真正清退，
//     其分区纳入协作式再均衡，且原持有分区作为一整批只移交给唯一新所有者；
//   - 旧进程（更低会话版本）随后的心跳、撤销确认、位点提交一律被会话栅栏
//     拒绝（ErrFencedSession），不能确认新版本撤销集合、也不能让位点倒退；
//   - 静态成员的幂等请求记录归属于实例本身，跨重连/接管持续生效；
//   - 若实例在撤销进行中断线，其撤销义务挂起：分区仍由它生效持有，重连后由新
//     会话确认，或保留期届满强制回收。
