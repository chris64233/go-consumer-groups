// Package consumergroups 提供消费组协调服务：以单调递增的分配版本
// （generation）隔离新旧成员操作，管理组成员、确定性分区分配、
// 协作式（cooperative）两阶段再均衡、会话超时与位点提交，并支持状态持久化。
//
// 协作式再均衡的核心不变量：
//   - 每次成员变化（加入/离开/超时剔除）都使分配版本 +1，并发布该版本的
//     目标所有权；新旧版本中所有者不变的分区「未受影响」，继续由原成员消费，
//     不会一次性撤销全部分区；
//   - 在两个存活成员之间转移的分区先进入待撤销状态：旧所有者确认撤销之前，
//     新所有者不能取得该分区（生效所有权仍指向旧所有者）；
//     无主分区立即分派，离开/超时成员的剩余分区由协调器强制回收；
//   - 撤销确认必须精确匹配组、成员、分配版本与分区集合，可幂等重试，
//     漏项、额外分区或旧版本确认一律被拒绝，不能提前完成整个再均衡；
//   - 全体义务成员确认完毕后版本在同一 generation 内收敛为 stable；
//   - 只有分区当前生效所有者能提交位点：待撤销分区在确认前可由旧所有者提交
//     最终位点，一旦转移完成，旧成员的迟到提交被所有权栅栏阻止；
//   - 心跳、离开、超时扫描与撤销确认在同一把锁内串行，只能推动一条单调的
//     版本状态机（stable -> revoking -> stable），全部协调状态持久化。
